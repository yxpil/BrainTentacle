// 轻量 i18n：模块级 store + useSyncExternalStore，localStorage 即时缓存 + bit.db 统一标记
// 语言标记入库（config.language）：Electron 托盘/任务面板同读一源，切换即生效。
// zh/en 随包；其余语言由 i18nExt 用外部引擎译好后 addDict 热加载进来。
// 词典是增量式的：某个扩展语言只译了一半也能立刻切过去用，缺的 key 逐级回退
// （目标语言 → en → zh → key 本身），界面不会因为少几条就露出空白。
// 用法：const { t, lang, setLang } = useLang();  t("nav.chat")
import { useSyncExternalStore } from "react";

const KEY = "bit.lang.v1";
const listeners = new Set();

// 语言码形状：xxx 或 xx-YYYY，其余一律当没设过。
// 这里必须挡一下——值会写进 html[lang] 并同步给主进程，脏字符串会污染托盘联动
const LANG_RE = /^[a-z]{2,3}(?:-[a-z0-9]{2,4})?$/;
const normLang = (v) => {
  const s = typeof v === "string" ? v.trim().toLowerCase() : "";
  return LANG_RE.test(s) ? s : "zh";
};

let current = normLang(localStorage.getItem(KEY));

// html[lang] 是语言联动的观察源（preload MutationObserver → 主进程 → 托盘面板）
function applyDom() {
  try { document.documentElement.lang = current; } catch { /* 非 DOM 环境兜底 */ }
}
applyDom();

function pushLang(lang) {
  // 数据库统一标记：best-effort，core 未就绪时静默（启动同步会补）
  try {
    const inv = window.__TAURI_INTERNALS__?.invoke;
    if (inv) inv("set_language", { language: lang }).catch?.(() => {});
  } catch { /* best-effort：窗口上下文不可用时静默 */ }
}

export function getLang() {
  return current;
}

// core 的 config.language 只收 zh/en（commands_api::set_language 会拒其他值），
// 扩展语言因此只活在渲染层：不推给后端，也不能被后端回读的值盖掉。
// 否则「生成日语 → 重启 → 被 DB 的 zh 打回原形」，而托盘本来就只有中英文案，不受影响。
const isExtLang = (code) => code !== "zh" && code !== "en";

export function setLang(lang) {
  current = normLang(lang);
  localStorage.setItem(KEY, current);
  applyDom();
  if (!isExtLang(current)) pushLang(current);
  listeners.forEach((l) => l());
}

/** 词典里已有的语言，zh/en 恒在前列，扩展语言按生成先后排 */
export function getAvailableLangs() {
  return Object.keys(dict);
}

/** 循环切换的下一门语言（标题栏按钮要用它写提示，不能只懂中英） */
export function nextLang() {
  const langs = getAvailableLangs();
  return langs[(langs.indexOf(current) + 1) % langs.length] || "zh";
}

export function toggleLang() {
  setLang(nextLang());
}

/** 词典变了但语言没变（生成完/清掉某个扩展语言）时，用它让界面重渲染 */
export function refreshLang() {
  listeners.forEach((l) => l());
}

/** 启动同步：以数据库为准（其他宿主/托盘改语言时保持一致）。best-effort，失败保持本地值 */
export function syncLangFromDb() {
  try {
    const inv = window.__TAURI_INTERNALS__?.invoke;
    if (!inv) return;
    Promise.resolve(inv("get_language", {}))
      .then((r) => {
        const db = normLang(r?.language);
        // 当前是扩展语言时以渲染层为准：DB 里那条只是上次的中英文选择
        if (isExtLang(current) || db === current) return;
        current = db;
        localStorage.setItem(KEY, current);
        applyDom();
        listeners.forEach((l) => l());
      })
      .catch(() => {});
  } catch { /* best-effort：调用通道不可用时静默 */ }
}

function subscribe(cb) {
  listeners.add(cb);
  return () => listeners.delete(cb);
}

// 空串按「没译到」处理：扩展词典可能先占位后补译，留着空串会把界面挖出空洞
const str = (v) => (typeof v === "string" && v ? v : undefined);

export function t(key, params) {
  // 第二参数既可以是插值对象，也可以是缺词时的兜底文案（调用方写 t(key, "中文") 时不会露出裸 key）
  const fallback = typeof params === "string" ? params : undefined;
  let s =
    str(dict[current]?.[key]) ??
    (current === "zh" ? undefined : str(dict.en?.[key])) ??
    str(dict.zh[key]) ??
    fallback ??
    key;
  if (params && typeof params === "object") {
    for (const k in params) {
      s = s.replace(new RegExp("\\{" + k + "\\}", "g"), params[k]);
    }
  }
  return s;
}

/** 语言 hook：返回 { lang, setLang, toggleLang, t }，切换时全应用重渲染 */
export function useLang() {
  useSyncExternalStore(subscribe, () => current);
  return { lang: current, setLang, toggleLang, t };
}

