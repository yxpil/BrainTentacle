export function addDict(entries) {
  for (const [lang, kv] of Object.entries(entries)) {
    if (!dict[lang]) dict[lang] = {};
    Object.assign(dict[lang], kv);
  }
}

/** 摘掉一门语言的运行期词典（清除扩展语言时要用，光删缓存留在词典里会继续生效） */
export function dropLang(lang) {
  if (lang === "zh" || lang === "en") return; // 随包词典不可删
  delete dict[lang];
}

/** 待译基准 key：以 zh 为准（zh 是唯一手写的完整词典） */
export function baseKeys() {
  return Object.keys(dict.zh);
}

/** 取某语言的词条副本，供翻译引擎读源文 */
export function getEntries(lang) {
  return dict[lang] ? { ...dict[lang] } : null;
}

export function hasLang(lang) {
  return !!dict[lang];
}
